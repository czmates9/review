		end

	end
	
	-- toto je společný pro všechny případy
	set @sql = @sql + '
			AND
			(
				(
					[POHYB POL].[SMER POHYB] = ' + CAST(@srcSmer AS CHAR(1)) + '
					AND [POHYB POL].[SKLAD ID] = ''' + @srcSklad + '''
					AND [POHYB POL].[ROK POHYB] = ' + @srcRok + '
