						[POHYB POL].[SMER POHYB]
						,[POHYB POL].[SKLAD ID]
						,[POHYB POL].[ROK POHYB]
						,[POHYB POL].[POHYB ID]
						,[POHYB POL].[POZICE POHYB POL]
						,[POHYB POL].[MAT ID]
						,[POHYB POL].[MNOZSTVI]
