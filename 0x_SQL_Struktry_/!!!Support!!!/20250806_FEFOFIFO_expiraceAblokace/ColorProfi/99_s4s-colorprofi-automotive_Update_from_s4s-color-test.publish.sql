CREATE   PROCEDURE [dbo].[procProdejAfterData4]
    @p2 NVarChar(20) -- cislo davky vlozenych dat (CZMST_DI.COUNTENTRIES)
AS
BEGIN
	SET NOCOUNT ON;

	IF NOT EXISTS (
	  SELECT * 
	  FROM   sys.columns 
	  WHERE  object_id = OBJECT_ID(N'[dbo].[CZMST_DI]') 
			 AND name = 'MTJ_ID'
	)
	ALTER TABLE [CZMST_DI] ADD [MTJ_ID] Int Not Null Default(0)	

	;WITH COUNTS 
	AS 
	( 
		SELECT [CountEntries], [SKL_ID], ROW_NUMBER() OVER(ORDER BY [SKL_ID] ASC) AS [ID] 
		FROM [CZMST_DI] 
		WHERE [CountEntries] = @p2
		--AND [SKL_ID_DEST] Is Not Null
		--AND [SKL_ID_DEST] <> ''
		GROUP BY [SKL_ID], [CountEntries] 
	)
	UPDATE
		[CZMST_DI] 
	SET 
		[MTJ_ID] = COUNTS.[ID]
	FROM 
		[CZMST_DI] as T1 INNER JOIN COUNTS
	ON 
		T1.[CountEntries] = COUNTS.[CountEntries]
		AND T1.[SKL_ID] = COUNTS.[SKL_ID]
	WHERE 
		T1.[CountEntries] = @p2
		--AND T1.[SKL_ID_DEST] Is Not Null
		--AND T1.[SKL_ID_DEST] <> ''


	-- pouštíme příjemky
	DECLARE @mtjID int
	DECLARE curTmp CURSOR FOR
		SELECT
			rtrim([CZMST_DI].[MTJ_ID])
		FROM
			[CZMST_DI]
		WHERE
			[CZMST_DI].[CountEntries] = @p2
			--AND [CZMST_DI].[SKL_ID_DEST] Is Not Null
			--AND [CZMST_DI].[SKL_ID_DEST] <> ''
		GROUP BY 
			[CZMST_DI].[MTJ_ID]

	OPEN curTmp
	FETCH NEXT FROM curTmp INTO @mtjID
	WHILE (@@FETCH_STATUS = 0) BEGIN
		exec [dbo].procProdejAfterData @mtjID, @p2
		FETCH NEXT FROM curTmp INTO @mtjID
	END
	CLOSE curTmp
	DEALLOCATE curTmp

END

