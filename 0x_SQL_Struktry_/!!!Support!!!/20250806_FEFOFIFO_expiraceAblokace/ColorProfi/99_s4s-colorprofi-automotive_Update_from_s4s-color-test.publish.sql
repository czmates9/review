				[' + @tableNameHeader + '].[CountEntries] = ' + @countEntries 

		
	end

	-- standardní lokační pohyb
	else begin
	
		if @tableName = 'CZMST_PI' begin
			set @lcnc = 'LOCNCODE'
		end
		else begin
			set @lcnc = 'LOCNCODEDEST'
		end

		set @sql = 'DECLARE curPohyb CURSOR FOR                               
					SELECT 
						[POHYB POL].[SMER POHYB]
						,[POHYB POL].[SKLAD ID]
						,[POHYB POL].[ROK POHYB]
						,[POHYB POL].[POHYB ID]
						,[POHYB POL].[POZICE POHYB POL]
						,[POHYB POL].[MAT ID]
						,[POHYB POL].[MNOZSTVI]
						,rtrim([' + @tableName + '].[SERLTNUM]) AS [SERLTNUM]
						,rtrim([' + @tableName + '].[LOCNCODE]) AS [LOCNCODE]
						,rtrim([' + @tableName + '].[' + @lcnc + ']) AS [LOCNCODEDEST]
			FROM
				[POHYB POL] INNER JOIN [' + @tableName + '] 
			ON
				[POHYB POL].[KGBARVA ID] = [' + @tableName + '].[DEX_ROW_ID]
