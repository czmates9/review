				[' + @tableName + '].[CountEntries] = [' + @tableNameHeader + '].[CountEntries])
			ON
				[POHYB POL].[MAT ID] = [' + @tableName + '].[TypPalID]
			AND [POHYB POL].[BIND ID] = [' + @tableName + '].[GUID]
