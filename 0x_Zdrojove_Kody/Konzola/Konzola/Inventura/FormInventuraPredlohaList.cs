        private void bwSkladPohyb_DoWork(object sender, DoWorkEventArgs e)
        {
            try
            {
                //bwLoadSkladPohyb.CancelAsync();
                Fask.Interfaces.Filtry.InventuraPredlohaListFiltr filtr = (Fask.Interfaces.Filtry.InventuraPredlohaListFiltr)e.Argument;
                Fask.Interfaces.DataSets.Inventura ds = new Fask.Interfaces.DataSets.Inventura();

                if (bwLoadSkladPohyb.CancellationPending)
                {
                    e.Cancel = true;
                    return;
                }

                // nacteni dat v oddelenem vlakne
                //ds = ((Fask.Interfaces.Inventura.IInventura)providerInventura).GetFiltrovanaPredloha(filtr);

                if ((providerInventura != null) && (providerInventura is Fask.Interfaces.Inventura.IInventura2_GetFiltrovanaPredloha))
                    ds = ((Fask.Interfaces.Inventura.IInventura2_GetFiltrovanaPredloha)providerInventura).GetFiltrovanaPredloha(filtr);
                else
                    throw new NotImplementedException("Provider neimplementuje IInventura2_GetFiltrovanaPredloha.");

                if (bwLoadSkladPohyb.CancellationPending)
                {
                    e.Cancel = true;
                    return;
                }

                e.Result = ds;
            }
            catch (Exception ex)
            {
                Fask.Logging.ExceptionHandler2.Handle(this.GetType().ToString(), System.Reflection.MethodBase.GetCurrentMethod().Name, ex);
            }
        }

        private void bwSkladPohyb_RunWorkerCompleted(object sender, RunWorkerCompletedEventArgs e)
        {
            try
            {
                // check error, check cancel, then use result
                if (e.Error != null)
                {
                    // handle the error
                    dsInventuraPredloha = new Fask.Interfaces.DataSets.Inventura();
                    bsInventuraPredloha.DataSource = dsInventuraPredloha;
                }
                else if (e.Cancelled)
                {
                    // handle cancellation
                    // TODO: maji se vymazat data z datasetu?? asi ano ...
                    //if (dsSkladPohyb == null)
                    dsInventuraPredloha = new Fask.Interfaces.DataSets.Inventura();
                    bsInventuraPredloha.DataSource = dsInventuraPredloha;
                }
                else
                {
                    // uspesne dokonceno ...
                    // use it on the UI thread
                    dsInventuraPredloha = (Fask.Interfaces.DataSets.Inventura)e.Result;
                    if (dsInventuraPredloha == null)
                        dsInventuraPredloha = new Fask.Interfaces.DataSets.Inventura();

                    bsInventuraPredloha.DataSource = dsInventuraPredloha;
                }

            }
            catch (Exception ex)
            {
                Fask.Logging.ExceptionHandler2.Handle(this.GetType().ToString(), System.Reflection.MethodBase.GetCurrentMethod().Name, ex);
                MessageBox.Show(ex.Message, this.Text, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            finally
            {
                ProgressIndicatorStop();
            }
        }

