        private void ui_comboBoxSKLIDActualize(Fask.Interfaces.DataSets.Sklady dsSkladyData)
        {
            // zajisteni zachovani vybranych hodnot

            var oldItems = comboBoxSKLID.Items;
            var oldSelectedItem = comboBoxSKLID.SelectedItem;
            var oldText = comboBoxSKLID.Text;

            comboBoxSKLID.Items.Clear();
            comboBoxSKLID.Items.AddRange(dsSkladyData.CZMST093.Select(null, "skl_desc asc"));

            if (oldItems.Count == 0)
                comboBoxSKLID.SelectedItem = null;
            if (!String.IsNullOrEmpty(oldText))
                comboBoxSKLID.Text = oldText;
            if (oldSelectedItem != null)
            {
                var osi = oldSelectedItem as Fask.Interfaces.DataSets.Sklady.CZMST093Row;
                if (osi != null)
                {
                    //var row = (Fask.Interfaces.DataSets.Sklady.CZMST093Row[])dsSkladyData.CZMST093.Select("skl_id=" + osi.skl_id);
                    var rows = dsSkladyData.CZMST093.Where(x => x.skl_id == osi.skl_id);
                    if (rows.Count() > 0)
                    {
                        comboBoxSKLID.SelectedItem = rows.First();
                    }
                }
            }

        }

